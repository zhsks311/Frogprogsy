    const realBin = join(home, "real-bin");
    const cmuxBin = join(home, "cmux-cli-shims");
    const fakeFrogp = join(home, process.platform === "win32" ? "fake-frogp.cmd" : "fake-frogp");
    const frogpOut = join(home, "frogp-args.txt");
    mkdirSync(realBin);
    mkdirSync(cmuxBin);
    executable(join(realBin, CLAUDE_EXE));
    executable(join(cmuxBin, CLAUDE_EXE));
    executable(
      fakeFrogp,
      process.platform === "win32"
        ? '@echo off\r\n> "%FROGP_OUT%" echo %FROGP_REAL_CLAUDE%\r\n:args\r\nif "%~1"=="" goto done\r\n>> "%FROGP_OUT%" echo %~1\r\nshift\r\ngoto args\r\n:done\r\n'
        : "#!/bin/sh\nprintf '%s\\n' \"$FROGP_REAL_CLAUDE\" > \"$FROGP_OUT\"\nfor arg in \"$@\"; do printf '%s\\n' \"$arg\" >> \"$FROGP_OUT\"; done\n",
    );
    process.env.FROGPROGSY_HOME = join(home, "frog");
    process.env.PATH = `${cmuxBin}${delimiter}${realBin}`;
    delete process.env.FROGP_REAL_CLAUDE;
    const realClaude = realpathSync.native(join(realBin, CLAUDE_EXE));
    const legacyPersonal = join(process.env.FROGPROGSY_HOME, "bin", "claude-personal");
    if (process.platform === "win32") {
      mkdirSync(join(process.env.FROGPROGSY_HOME, "bin"), { recursive: true });
      writeFileSync(legacyPersonal, "# Generated by frogprogsy\n", "utf8");
    }

    const result = syncClaudeLauncherShims(config(), { frogpCommand: [fakeFrogp] });

    expect(result.realClaude).toBe(realClaude);
    expect(result.frogpCommand).toEqual([fakeFrogp]);
    expect(result.launchers.some(entry => entry.name === "claude-personal" && entry.profileId === "cp_personal")).toBe(true);
    const personal = join(result.binDir, claudeLauncherFileName("claude-personal"));
    expect(existsSync(personal)).toBe(true);
    if (process.platform === "win32") expect(existsSync(legacyPersonal)).toBe(false);
    const script = readFileSync(personal, "utf8");
    expect(script).toContain("Generated by frogprogsy");
    if (process.platform === "win32") {
      expect(script).toContain(`set "FROGP_REAL_CLAUDE=${realClaude}"`);
      expect(script).toContain(`"${fakeFrogp}" "claude" "run" "cp_personal" "--" %*`);
      expect(script).not.toContain("#!/bin/sh");
    } else {
      expect(script).toContain(`FROGP_REAL_CLAUDE='${realClaude}'`);
      expect(script).toContain(`exec '${fakeFrogp}' 'claude' 'run' 'cp_personal' '--' "$@"`);
      expect(script).not.toContain("exec frogp ");
    }
    const executed = process.platform === "win32"
      ? spawnSync(`"${personal}" --version`, {
          shell: true,
          env: { ...process.env, FROGP_OUT: frogpOut },
          encoding: "utf8",
        })
      : spawnSync(personal, ["--version"], {
          env: { ...process.env, FROGP_OUT: frogpOut, PATH: "/usr/bin:/bin" },
          encoding: "utf8",
        });
