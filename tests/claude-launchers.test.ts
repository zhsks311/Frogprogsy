function executable(path: string, content = "#!/bin/sh\nexit 0\n") {
  writeFileSync(path, content, "utf8");
  chmodSync(path, 0o755);
}

function managedLauncherBytes(profileId = "cp_old"): string {
  return process.platform === "win32"
    ? `@echo off\r\nrem Generated by frogprogsy. Do not edit by hand.\r\n"frogp" "claude" "run" "${profileId}" "--" %*\r\n`
    : `#!/bin/sh\n# Generated by frogprogsy. Do not edit by hand.\nexec 'frogp' 'claude' 'run' '${profileId}' '--' "$@"\n`;
}

