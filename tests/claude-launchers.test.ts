    const maxManagedBytes = 1024 * 1024;
    const legacyPrefix = process.platform === "win32"
      ? "rem Generated by frogprogsy\r\nrem "
      : "# Generated by frogprogsy\n# ";
    const initialSize = maxManagedBytes - Buffer.byteLength(recoverySuffix, "utf8");
    const legacyBytes = legacyPrefix + "x".repeat(initialSize - Buffer.byteLength(legacyPrefix, "utf8"));
    const partialBytes = process.platform === "win32"
      ? Buffer.byteLength("@echo off\r\nrem Generated by frogprogs", "utf8")
      : Buffer.byteLength("#!/bin/sh\n# Generated by frogprogs", "utf8");
    mkdirSync(binDir, { recursive: true });
