    expect(errors.messages.join("\n")).not.toContain(registered);
    expect(errors.messages.join("\n")).not.toContain(other);
    expect(errors.messages.join("\n")).toContain("claude-anthropic-work");

    rmSync(root, { recursive: true, force: true });
