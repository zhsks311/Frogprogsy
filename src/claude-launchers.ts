function removeManagedLauncherFile(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  target: string,
  options: ClaudeLauncherSyncOptions,
  warnings: string[],
): boolean {
  if (resolve(dirname(target)) !== resolve(binDir)
    || !launcherDirectoryHasIdentity(binDir, binIdentity)) return false;
  const ownership = classifyLauncherTarget(target, options.readManagedLauncherChunk);
  if (ownership.kind === "unsafe-managed") {
    warnings.push(`launcher ${basename(target)} cleanup skipped; managed target has multiple hard links`);
    return false;
  }
  if (ownership.kind === "unsafe-managed-size") {
    warnings.push(`launcher ${basename(target)} cleanup skipped; managed target exceeds the safe update size`);
    return false;
  }
  if (ownership.kind !== "managed") return false;

  const recovery = createRemovalRecovery(binDir, binIdentity, target, ownership);
  if (!recovery) {
    warnings.push(`launcher ${basename(target)} cleanup skipped; durable recovery could not be prepared`);
    return false;
  }
  try {
    options.beforeManagedRemove?.(target);
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
      warnings.push(`launcher ${basename(target)} cleanup skipped; launcher directory changed before capture`);
      return false;
    }
    renameSync(target, recovery.capture);
  } catch (error) {
    if (launcherDirectoryHasIdentity(binDir, binIdentity)) removeRecoveryOperation(recovery.operationDir);
    if (options.beforeManagedRemove && fsErrorCode(error) !== undefined) {
      warnings.push(`launcher ${basename(target)} cleanup skipped; target changed before capture`);
    }
    return false;
  }
  options.beforeManagedRemoveDurability?.(target);
  const syncDirectory = options.fsyncDirectory ?? fsyncDirectory;
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)
    || !syncDirectory(binDir)
    || !syncDirectory(recovery.operationDir)) {
    warnings.push(`launcher ${basename(target)} cleanup deferred; captured target could not be durably recorded`);
    return false;
  }
  options.afterManagedRemoveCapture?.(target);
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
    warnings.push(`launcher ${basename(target)} cleanup deferred; launcher directory changed after capture`);
    return false;
  }
  const manifest = readRemovalManifest(recovery.operationDir, options.readManagedLauncherChunk);
  if (!manifest) {
    warnings.push(`launcher ${basename(target)} cleanup deferred; recovery record could not be read`);
    return false;
  }
  const outcome = finishRemovalRecovery(
    binDir,
    binIdentity,
    recovery.operationDir,
    manifest,
    options.readManagedLauncherChunk,
    options.afterForeignRestore,
    options.fsyncDirectory ?? fsyncDirectory,
  );
  if (outcome.warning) warnings.push(outcome.warning);
  return outcome.removed;
}

function hasManagedLauncherFile(binDir: string): boolean {
  let entries: string[];
  try {
    entries = readdirSync(binDir);
  } catch {
    return false;
  }
  return entries.some(fileName => {
    const logicalName = process.platform === "win32" && fileName.endsWith(".cmd")
      ? fileName.slice(0, -4)
      : fileName;
    if (!(logicalName === "claude" || SHORTCUT_NAME_PATTERN.test(logicalName))) return false;
    const ownership = classifyLauncherTarget(join(binDir, fileName));
    return ownership.kind === "managed"
      || ownership.kind === "unsafe-managed"
      || ownership.kind === "unsafe-managed-size";
  });
}

/**
 * Remove marked launchers whose logical names no longer appear in the current plan, even when the
 * manifest is missing or corrupt. The classifier — not the manifest — is the deletion authority, so
 * unmarked user files and unsafe managed inodes are preserved. Same-name launchers are validated
 * against the exact profile separately before they are reported or rewritten.
 */
function removeOrphanManagedLaunchers(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  nextNames: Set<string>,
  options: ClaudeLauncherSyncOptions,
  warnings: string[],
): string[] {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return [];
  let entries: string[];
  try {
    entries = readdirSync(binDir);
  } catch {
    return [];
  }

  const removed = new Set<string>();
  for (const fileName of entries) {
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) break;
    const logicalName = process.platform === "win32" && fileName.endsWith(".cmd")
      ? fileName.slice(0, -4)
      : fileName;
    if (!(logicalName === "claude" || /^claude-[a-z0-9][a-z0-9-]*$/.test(logicalName))) continue;
    if (nextNames.has(logicalName)) continue;
    if (removeManagedLauncherFile(binDir, binIdentity, join(binDir, fileName), options, warnings)) {
      removed.add(logicalName);
    }
  }
  return [...removed];
}

interface LauncherDirectoryIdentity {
  dev: number;
  ino: number;
}

function launcherDirectoryHasIdentity(binDir: string, identity: LauncherDirectoryIdentity): boolean {
  try {
    const current = lstatSync(binDir);
    return current.isDirectory()
      && !current.isSymbolicLink()
      && current.dev === identity.dev
      && current.ino === identity.ino;
  } catch {
    return false;
  }
}

function prepareLauncherDirectory(configDir: string): { binDir: string; identity: LauncherDirectoryIdentity } {
  const binDir = join(configDir, "bin");
  try {
    lstatSync(binDir);
  } catch (error) {
    if (fsErrorCode(error) !== "ENOENT") {
      throw new Error("Claude launcher directory could not be inspected");
    }
    try {
      mkdirSync(binDir, { mode: 0o700 });
    } catch (mkdirError) {
      if (fsErrorCode(mkdirError) !== "EEXIST") {
        throw new Error("Claude launcher directory could not be created");
      }
    }
  }

  const pathStat = lstatSync(binDir);
  if (!pathStat.isDirectory() || pathStat.isSymbolicLink()) {
    throw new Error("Claude launcher directory must be a real directory");
  }
  if (process.platform === "win32") {
    const identity = { dev: pathStat.dev, ino: pathStat.ino };
    if (!launcherDirectoryHasIdentity(binDir, identity)) {
      throw new Error("Claude launcher directory changed before use");
    }
    return { binDir, identity };
  }

  let fd: number | undefined;
  try {
    fd = openSync(binDir, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
    const opened = fstatSync(fd);
    if (!opened.isDirectory() || opened.dev !== pathStat.dev || opened.ino !== pathStat.ino) {
      throw new Error("Claude launcher directory changed while it was being opened");
    }
    fchmodSync(fd, 0o700);
    fsyncSync(fd);
    const identity = { dev: opened.dev, ino: opened.ino };
    if (!launcherDirectoryHasIdentity(binDir, identity)) {
      throw new Error("Claude launcher directory changed before use");
    }
    return { binDir, identity };
  } catch (error) {
    if (error instanceof Error && error.message.startsWith("Claude launcher directory")) throw error;
    throw new Error("Claude launcher directory could not be opened safely");
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
  }
}

function managedContentMatchesProfile(content: string, profileId: string): boolean {
  const invocation = process.platform === "win32"
    ? `"claude" "run" "${profileId}" "--"`
    : `'claude' 'run' '${profileId}' '--'`;
  return content.includes(MANAGED_MARKER) && content.includes(invocation);
}

export const REAL_CLAUDE_UNRESOLVED_WARNING =
  "the original Claude Code executable was not found, so no account shortcut was generated; install Claude Code and run frogp refresh";

export function syncClaudeLauncherShims(
  config: FrogConfig,
  options: ClaudeLauncherSyncOptions = {},
): ClaudeLauncherSyncResult {
  const configDir = getConfigDir();
  const binDir = join(configDir, "bin");
  const frogpCommand = options.frogpCommand ?? currentFrogpCommand();
  const plan = plannedClaudeLaunchers(config);
  const previous = readManifest();
  const realClaude = options.realClaude ?? findRealClaudeExecutableOrNull([binDir]);

  // Missing Claude on a fresh installation is an inspection result, not a reason to create config,
  // launcher, or manifest files. Existing managed state still proceeds through durable cleanup.
  if (!realClaude
    && previous === null
    && !hasManagedLauncherFile(binDir)
    && ownedRecoveryRoot(binDir, false) === null) {
    return {
      binDir,
      realClaude: "claude",
      realClaudeResolved: false,
      frogpCommand,
      launchers: [],
      removed: [],
      warnings: [...plan.warnings, REAL_CLAUDE_UNRESOLVED_WARNING],
    };
  }

  ensureConfigDirForWrite("sync Claude launcher shims");
  const { identity: binIdentity } = prepareLauncherDirectory(configDir);
  const warnings = [
    ...plan.warnings,
    ...recoverLauncherRemovals(
      binDir,
      binIdentity,
      options.readManagedLauncherChunk,
      options.afterForeignRestore,
      options.fsyncDirectory ?? fsyncDirectory,
    ),
  ];
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
    throw new Error("Claude launcher directory changed before synchronization");
  }

  const candidates: Array<{ entry: ClaudeLauncherEntry; ownership: LauncherTargetOwnership }> = [];
  for (const entry of plan.launchers) {
    const target = join(binDir, claudeLauncherFileName(entry.name));
    const ownership = classifyLauncherTarget(target, options.readManagedLauncherChunk);
    if (ownership.kind === "absent" || ownership.kind === "managed") {
      candidates.push({ entry, ownership });
      continue;
    }
    const reason = ownership.kind === "unsafe-managed"
      ? "managed target has multiple hard links"
      : ownership.kind === "unsafe-managed-size"
        ? "managed target exceeds the safe update size"
        : "target is not owned by frogprogsy. Move or remove it, then run frogp refresh";
    warnings.push(`launcher ${entry.name} skipped for ${entry.profileName}; ${reason}`);
  }
  const nextNames = new Set(plan.launchers.map(entry => entry.name));
  const removed: string[] = [];

  for (const old of previous?.launchers ?? []) {
    if (nextNames.has(old.name)) {
      if (process.platform === "win32") {
        removeManagedLauncherFile(binDir, binIdentity, join(binDir, old.name), options, warnings);
      }
      continue;
    }
    let didRemove = false;
    for (const target of launcherTargetPaths(binDir, old.name)) {
      didRemove = removeManagedLauncherFile(binDir, binIdentity, target, options, warnings) || didRemove;
    }
    if (didRemove) removed.push(old.name);
  }

  // Cleanup does not depend on the native executable. Run it first so deleted or renamed accounts
  // lose stale managed launchers even while Claude Code itself is absent.
  for (const orphan of removeOrphanManagedLaunchers(binDir, binIdentity, nextNames, options, warnings)) {
    if (!removed.includes(orphan)) removed.push(orphan);
  }

  if (!realClaude) {
    // A same-name launcher for another profile is not a valid survivor. Without a native executable
    // it cannot be rewritten, so remove it through the same journaled generated-only cleanup path.
    for (const entry of plan.launchers) {
      const target = join(binDir, claudeLauncherFileName(entry.name));
      const ownership = classifyLauncherTarget(target, options.readManagedLauncherChunk);
      if (ownership.kind !== "managed" || managedContentMatchesProfile(ownership.content, entry.profileId)) continue;
      if (removeManagedLauncherFile(binDir, binIdentity, target, options, warnings) && !removed.includes(entry.name)) {
        removed.push(entry.name);
      }
    }

    const surviving = plan.launchers.filter(entry => {
      const ownership = classifyLauncherTarget(
        join(binDir, claudeLauncherFileName(entry.name)),
        options.readManagedLauncherChunk,
      );
      return ownership.kind === "managed"
        && managedContentMatchesProfile(ownership.content, entry.profileId);
    });
    const manifest: ClaudeLauncherManifest = {
      schemaVersion: 1,
      generatedAt: new Date().toISOString(),
      binDir,
      realClaude: previous?.realClaude ?? "claude",
      frogpCommand: previous?.frogpCommand ?? frogpCommand,
      launchers: surviving,
    };
    atomicWriteFile(manifestPath(), JSON.stringify(manifest, null, 2) + "\n");
    return {
      binDir,
      realClaude: "claude",
      realClaudeResolved: false,
      frogpCommand,
      launchers: surviving,
      removed,
      warnings: [...warnings, REAL_CLAUDE_UNRESOLVED_WARNING],
    };
  }

  const installed: ClaudeLauncherEntry[] = [];
  for (const { entry, ownership } of candidates) {
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
      throw new Error("Claude launcher directory changed during synchronization");
    }
    const target = join(binDir, claudeLauncherFileName(entry.name));
    const content = launcherScript(entry, realClaude, frogpCommand);
    if (publishManagedLauncher(
      binDir,
      binIdentity,
      target,
      entry,
      ownership,
      content,
      options.beforePublish,
      options.readManagedLauncherChunk,
      options.writeManagedLauncherChunk,
      options.fsyncDirectory ?? fsyncDirectory,
    )) {
      installed.push(entry);
    } else {
      warnings.push(`launcher ${entry.name} skipped for ${entry.profileName}; target changed or could not be published safely`);
    }
    if (process.platform === "win32") {
      removeManagedLauncherFile(binDir, binIdentity, join(binDir, entry.name), options, warnings);
    }
  }

  const manifest: ClaudeLauncherManifest = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    binDir,
    realClaude,
    frogpCommand,
    launchers: installed,
  };
  atomicWriteFile(manifestPath(), JSON.stringify(manifest, null, 2) + "\n");
  return { binDir, realClaude, realClaudeResolved: true, frogpCommand, launchers: installed, removed, warnings };
}

