/** Fixed exit code for a refused launch whose caller environment names a different account home. */
export const CLAUDE_HOME_CONFLICT_EXIT_CODE = 78;

export interface ClaudeHomeConflict {
  /** Which environment variable disagreed, or `both` when the two disagree with each other. */
  source: "CLAUDE_CONFIG_DIR" | "CLAUDE_HOME" | "both";
  reason: "different-home" | "unreadable" | "registered-unreadable";
}

/**
 * Compare the caller-supplied account home against the profile's registered home.
 *
 * Returns `null` when the launch may proceed: nothing set, or every set value canonically names the
 * same directory. Otherwise returns the conflict to refuse on.
 *
 * Refusing rather than warning is deliberate. A warning still lets Claude Code write credentials into
 * the wrong scoped store — the Keychain service name derives from the home path — which is exactly the
 * Probe-B damage recorded in `structure/09_claude-dual-auth.md`. Recovery required a human re-login.
 *
 * Missing paths, non-directories, and unreadable paths are fail-closed: an unresolvable value cannot be
 * proven equal to the registered home, so it is treated as a conflict rather than ignored.
 */
export function detectClaudeHomeConflict(
  registeredHome: string,
  env: NodeJS.ProcessEnv = process.env,
): ClaudeHomeConflict | null {
  const configDir = env.CLAUDE_CONFIG_DIR?.trim();
  const claudeHome = env.CLAUDE_HOME?.trim();

  // The registered home is the source of truth. It is never rewritten by this comparison: the spawn
  // below uses `profile.claudeHome` verbatim, because that exact string is the credential address.
  const registered = canonicalDirIdentity(registeredHome);
  if (registered === null) {
    return { source: configDir ? "CLAUDE_CONFIG_DIR" : claudeHome ? "CLAUDE_HOME" : "both", reason: "registered-unreadable" };
  }
  if (!configDir && !claudeHome) return null;

  const entries: Array<{ source: "CLAUDE_CONFIG_DIR" | "CLAUDE_HOME"; raw: string }> = [];
  if (configDir) entries.push({ source: "CLAUDE_CONFIG_DIR", raw: configDir });
  if (claudeHome) entries.push({ source: "CLAUDE_HOME", raw: claudeHome });

  const identities: string[] = [];
  for (const entry of entries) {
    const identity = canonicalDirIdentity(entry.raw);
    if (identity === null) return { source: entry.source, reason: "unreadable" };
    if (registered !== null && identity !== registered) {
      return { source: entry.source, reason: "different-home" };
    }
    identities.push(identity);
  }

  // Both set but pointing at different directories: refuse even if neither matched the registered home
  // path textually (e.g. the registered home itself could not be resolved).
  if (identities.length === 2 && identities[0] !== identities[1]) {
    return { source: "both", reason: "different-home" };
  }
  return null;
}

/** Canonical identity of an existing directory, or `null` when it is missing, not a directory, or unreadable. */
function canonicalDirIdentity(path: string): string | null {
  try {
    const resolved = resolve(expandTildePath(path));
    const stat = statSync(resolved);
    if (!stat.isDirectory()) return null;
    return realpathSync.native(resolved);
  } catch {
    return null;
  }
}

function expandTildePath(path: string): string {
  if (path === "~") return homedir();
  if (path.startsWith(`~${sep}`) || path.startsWith("~/")) return join(homedir(), path.slice(2));
  return path;
}

/**
 * User-facing refusal text. Names the shortcut and the fixing command; never prints a full home path.
 * Privacy-safe paths belong to `frogp doctor claude`, not to this default message.
 */
export function claudeHomeConflictMessage(conflict: ClaudeHomeConflict, shortcutName: string): string {
  if (conflict.reason === "registered-unreadable") {
    return [
      `Refusing to start: the registered Claude account home for ${shortcutName} is missing or cannot be read.`,
      "Running anyway could write credentials to an unintended location.",
      `Fix: restore that account home or remove and add the ${shortcutName} account again.`,
    ].join("\n");
  }
  const varLabel = conflict.source === "both" ? "CLAUDE_CONFIG_DIR and CLAUDE_HOME" : conflict.source;
  const cause = conflict.reason === "unreadable"
    ? `${varLabel} names a directory that cannot be read.`
    : `${varLabel} names a different Claude account than ${shortcutName} uses.`;
  return [
    `Refusing to start: ${cause}`,
    "Running anyway could sign this account into the wrong Claude home.",
    `Fix: unset that variable and run ${shortcutName} again, or run your own claude command directly.`,
  ].join("\n");
}

export async function runClaudeProfile(
  profile: ClaudeProfileRecord,
  config: FrogConfig,
  claudeArgs: string[],
  options: RunClaudeProfileOptions = {},
): Promise<never> {
  const exit = options.exit ?? ((code: number) => process.exit(code));

  // Single convergence point for every managed launch: a generated shortcut runs
  // `frogp claude run <id> --`, and `frogp claude run` is invoked directly. Both land here. The check
  // runs before catalog prewrite, environment assembly, and spawn, so a refusal writes nothing.
  const conflict = detectClaudeHomeConflict(profile.claudeHome, options.env ?? process.env);
  if (conflict) {
    const command = profile.id === config.claudeProfiles?.defaultProfileId ? "claude" : claudeProfileShortcutName(profile);
    console.error(claudeHomeConflictMessage(conflict, command));
    return exit(CLAUDE_HOME_CONFLICT_EXIT_CODE);
  }

  // Validate whichever executable we are about to spawn — the explicit `FROGP_REAL_CLAUDE` a generated
  // shortcut passes through the CLI, or the resolver's pick. Validating only inside the resolver would
  // skip the shortcut path entirely, since an explicit value short-circuits it.
  const validateExecutable = options.validateExecutable ?? assertRealClaudeExecutable;
  const realClaude = validateExecutable(options.realClaude ?? findRealClaudeExecutable());
  const useGateway = options.gateway ?? gatewayProcessActive();
  const spawn = options.spawn ?? spawnSync;
  let env: NodeJS.ProcessEnv;
  if (useGateway) {
    // Sync this profile's picker cache before the real Claude process starts, then launch.
    await refreshManagedProfileCatalog(config, profile, options.refreshCatalog);
    const carrier = config.gatewayAuthCarrier ?? "token-free";
    const runtimeAccessToken = config.localAccess?.enabled === true ? readLocalAccessToken() ?? undefined : undefined;
    env = buildClaudeProfileRunEnv(profile, readActivePort() ?? config.port ?? DEFAULT_PORT, carrier, process.env, runtimeAccessToken);
  } else {
    env = buildClaudeProfileNativeEnv(profile);
  }
  const result = spawn(realClaude, claudeArgs, { stdio: "inherit", env });
  return exit(launcherResultExitCode(result));
}

export function runNativeClaude(
  claudeArgs: string[],
  options: { realClaude?: string; spawn?: typeof spawnSync; exit?: (code: number) => never } = {},
): never {
  const realClaude = options.realClaude ?? findRealClaudeExecutable();
  const spawn = options.spawn ?? spawnSync;
  const exit = options.exit ?? ((code: number) => process.exit(code));
  const result = spawn(realClaude, claudeArgs, { stdio: "inherit", env: process.env });
  return exit(launcherResultExitCode(result));
}

export function profileForLauncherName(config: FrogConfig, launcherName: string): ClaudeProfileRecord {
  const { launchers } = plannedClaudeLaunchers(config);
  const matched = launchers.find(entry => entry.name === launcherName);
  return resolveClaudeProfile(config, matched?.profileId ?? launcherName.replace(/^claude-/, ""));
}
