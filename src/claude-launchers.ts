interface ManagedTargetIdentity {
  kind: "managed";
  dev: number;
  ino: number;
  content: string;
  size: number;
  sha256: string;
  recoverySuffixPresent: boolean;
}

type LauncherTargetOwnership =
  | { kind: "absent" }
  | ManagedTargetIdentity
  | { kind: "unsafe-managed" }
  | { kind: "unsafe-managed-size" }
  | { kind: "foreign" };

