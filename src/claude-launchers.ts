function realpathMaybe(path: string): string {
  try { return realpathSync.native(path); } catch { return resolve(path); }
}

function isExecutableFile(path: string): boolean {
  if (!existsSync(path)) return false;
  try {
    const real = realpathMaybe(path);
    return existsSync(real);
  } catch {
    return false;
  }
}

/**
 * Shared source of truth: is `path` a frogprogsy Claude launcher of ANY form — a generated shim
 * (carries {@link MANAGED_MARKER}) or a source entrypoint that delegates to `runClaudeLauncherProcess`
 * ({@link LAUNCHER_SOURCE_MARKER}) — regardless of its worktree location or symlink chain? Only a
 * bounded head prefix is read, so a real native Claude binary is never slurped whole. Fails closed:
 * any unexpected read/I/O error is treated as "is a launcher" so a suspect candidate is skipped or
 * rejected rather than trusted. Callers pass the canonical (already realpath-resolved) path.
 */
export function isFrogprogsyClaudeLauncher(path: string): boolean {
  let fd: number | undefined;
  try {
    fd = openSync(path, "r");
    const buffer = Buffer.alloc(LAUNCHER_SNIFF_BYTES);
    const bytesRead = readSync(fd, buffer, 0, LAUNCHER_SNIFF_BYTES, 0);
    const head = buffer.toString("utf8", 0, bytesRead);
    return head.includes(MANAGED_MARKER) || head.includes(LAUNCHER_SOURCE_MARKER);
  } catch {
    return true;
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
  }
}

function currentPackageSrcDir(): string {
  return realpathMaybe(dirname(process.argv[1] ?? "."));
}

function isInside(parent: string, child: string): boolean {
  const p = realpathMaybe(parent);
  const c = realpathMaybe(child);
  return c === p || c.startsWith(`${p}${sep}`);
}

export function findRealClaudeExecutable(extraSkipDirs: string[] = []): string {
  const explicit = process.env.FROGP_REAL_CLAUDE?.trim();
  if (explicit && isExecutableFile(explicit)) return realpathMaybe(explicit);

  const skipDirs = [claudeLauncherBinDir(), currentPackageSrcDir(), ...extraSkipDirs].map(realpathMaybe);
  const candidates = claudeExecutableCandidates();
  const pathEntries = (process.env.PATH ?? "").split(delimiter).filter(Boolean);
  for (const dir of pathEntries) {
    const resolvedDir = realpathMaybe(dir);
    if (resolvedDir.includes("cmux-cli-shims")) continue;
    if (skipDirs.some(skip => resolvedDir === skip || resolvedDir.startsWith(`${skip}${sep}`))) continue;
    // Honor PATHEXT-like suffixes on Windows: probe each candidate name in preference order within
    // this dir before moving on. POSIX has a single candidate (`claude`), so behavior is unchanged.
    for (const name of candidates) {
      const candidate = join(dir, name);
      if (!isExecutableFile(candidate)) continue;
      const real = realpathMaybe(candidate);
      if (real.includes("cmux-cli-shims")) continue;
      if (skipDirs.some(skip => real === skip || real.startsWith(`${skip}${sep}`))) continue;
      if (isFrogprogsyClaudeLauncher(real)) continue;
      return real;
    }
  }
  throw new Error("No safe Claude executable was found outside frogprogsy-managed paths");
}

/**
 * Best-effort variant for cleanup and shortcut generation. Spawn paths keep using the throwing
 * resolver so a missing executable can never degrade into an interceptable bare `claude`.
 */
export function findRealClaudeExecutableOrNull(extraSkipDirs: string[] = []): string | null {
  try {
    return findRealClaudeExecutable(extraSkipDirs);
  } catch {
    return null;
  }
}

/**
 * Validate that `candidate` is a REAL Claude executable safe to spawn. Rejects:
 *  - empty / non-absolute values (e.g. bare `claude`, which a frogprogsy shim on PATH can intercept),
 *  - non-existent paths, directories, and any non-file target,
 *  - zero-byte or non-executable Claude update artifacts (verified with `accessSync(real, X_OK)`),
 *  - anything inside the frogprogsy launcher bin dir or the frogprogsy source dir,
 *  - any frogprogsy launcher — generated shim OR source entrypoint delegating to
 *    `runClaudeLauncherProcess`, in any worktree — detected from a bounded head prefix, including via symlink.
 * Symlinks are resolved to their canonical real target before every check, and that canonical path is
 * returned. Error messages carry only a fixed reason — never the candidate path, a token, or a credential.
 *
 * Lives here rather than in `claude-grants.ts` because every check it performs depends on this module
 * (launcher bin dir, launcher detection, source dir); grants imports it, so the reverse direction would cycle.
 */
export function assertRealClaudeExecutable(candidate: string | undefined): string {
  const raw = (candidate ?? "").trim();
  if (!raw) {
    throw new Error("a real Claude executable is required, got an empty value");
  }
  if (!isAbsolute(raw)) {
    throw new Error('a non-absolute executable is refused; bare "claude" can be intercepted by a frogprogsy shim');
  }
  if (!existsSync(raw)) {
    throw new Error("the Claude executable does not exist");
  }
  // Resolve symlinks up front so every check below runs on the canonical real target: a symlink that
  // points at a managed launcher, the launcher bin dir, or the source dir is rejected by its real path.
  const real = realpathMaybe(raw);
  let stat;
  try {
    stat = statSync(real);
  } catch {
    throw new Error("the Claude executable is not accessible");
  }
  if (!stat.isFile()) {
    throw new Error("the Claude executable is not a file");
  }
  if (stat.size === 0) {
    // A cleared / partially-written Claude self-update artifact reads as a zero-byte file.
    throw new Error("the Claude executable is not executable");
  }

  if (isInside(claudeLauncherBinDir(), real)) {
    throw new Error("the frogprogsy launcher directory is refused as a Claude executable");
  }
  if (isInside(currentPackageSrcDir(), real)) {
    throw new Error("the frogprogsy source directory is refused as a Claude executable");
  }
  // Reject any frogprogsy launcher — a generated shim or a source entrypoint that delegates to
  // `runClaudeLauncherProcess` — via the shared bounded-head detector. Only a prefix is read, so a real
  // native Claude binary is never slurped whole, and it fails closed on unexpected read/I/O errors.
  if (isFrogprogsyClaudeLauncher(real)) {
    throw new Error("a managed frogprogsy launcher is refused as a Claude executable");
  }
  // Windows has no POSIX exec bit, so `accessSync(X_OK)` accepts any readable file — including an
  // extensionless, non-runnable one. The real "is executable" contract there is the PATHEXT-like
  // suffix, so require a recognized executable extension (.exe/.cmd/.bat/.com). POSIX is untouched and
  // keeps exact X_OK semantics. This runs after the launcher/dir/source gates so those keep their
  // specific rejection messages.
  if (process.platform === "win32" && !hasWindowsExecutableSuffix(real)) {
    throw new Error("the Claude executable is not executable");
  }
  // Final gate: the canonical target must actually be executable by this process on this platform.
  try {
    accessSync(real, constants.X_OK);
  } catch {
    throw new Error("the Claude executable is not executable");
  }
  return real;
}

function slugify(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
}

/**
 * Command-name shape frogprogsy is allowed to own: `claude-<something>`, never bare `claude`.
 *
 * The trailing group is mandatory. frogprogsy never owns the plain `claude` command — that name always
 * belongs to the user's own Claude Code installation.
 */
const SHORTCUT_NAME_PATTERN = /^claude-[a-z0-9][a-z0-9-]*$/;

/**
 * The one stable command name for a profile.
 *
 * Derived from the profile name, which the user chooses and can change with `frogp claude rename`. The
 * home path is deliberately not used: it is a credential address (the Keychain service name hashes it),
 * so it must not move, which makes it a poor source for a renameable command.
 *
 * Falls back to the profile id when the name yields nothing usable. Non-ASCII names slugify to an empty
 * string — `slugify("업무")` is `""` — and an empty suffix would produce bare `claude`, so the fallback
 * is what keeps such profiles nameable at all.
 */
export function claudeProfileShortcutName(profile: ClaudeProfileRecord): string {
  const fromName = slugify(profile.name);
  const candidate = fromName.startsWith("claude-") ? fromName : `claude-${fromName}`;
  if (SHORTCUT_NAME_PATTERN.test(candidate)) return candidate;

  const fromId = slugify(profile.id.replace(/^cp_/, ""));
  const fallback = `claude-${fromId}`;
  return SHORTCUT_NAME_PATTERN.test(fallback) ? fallback : `claude-profile`;
}

function profileLauncherNames(profile: ClaudeProfileRecord, isDefault: boolean): string[] {
  // The default profile uses the user's native `claude` command directly. frogprogsy creates shortcuts
  // only for additional accounts, so there is no redundant `claude-default` command to learn or maintain.
  if (isDefault) return [];

  // Exactly one shortcut per additional profile. Generating a home-basename alias alongside a name alias
  // produced several commands for one account and left the stale one behind after a rename.
  //
  // The filter is the enforcement point, not the proposal sites. `slugify` strips non-ASCII to `-` and
  // then trims it, so a home like `.claude-업무` collapses to exactly `claude` — plain-name ownership
  // could reappear from ordinary user input, no matter how many individual proposals were removed.
  return [claudeProfileShortcutName(profile)].filter(name => SHORTCUT_NAME_PATTERN.test(name));
}

export function plannedClaudeLaunchers(config: FrogConfig): { launchers: ClaudeLauncherEntry[]; warnings: string[] } {
  const profiles = managedClaudeProfiles(config);
  const defaultId = config.claudeProfiles?.defaultProfileId ?? profiles[0]?.id;
  const seen = new Map<string, string>();
  const launchers: ClaudeLauncherEntry[] = [];
  const warnings: string[] = [];

  for (const profile of profiles) {
    for (const name of profileLauncherNames(profile, profile.id === defaultId)) {
      const existing = seen.get(name);
      if (existing && existing !== profile.id) {
        warnings.push(`launcher ${name} skipped for ${profile.name}; already assigned to ${existing}`);
        continue;
      }
      if (existing) continue;
      seen.set(name, profile.id);
      launchers.push({ name, profileId: profile.id, profileName: profile.name, claudeHome: profile.claudeHome });
    }
  }
  launchers.sort((a, b) => a.name.localeCompare(b.name));
  return { launchers, warnings };
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
function cmdQuote(value: string): string {
  return `"${value.replace(/%/g, "%%")}"`;
}

function currentFrogpCommand(): string[] {
  const main = process.argv[1];
  if (main && existsSync(main)) return [process.execPath, realpathMaybe(main)];
  return ["frogp"];
}

function launcherExecLine(frogpCommand: string[], entry: ClaudeLauncherEntry): string {
  const command = [...frogpCommand, "claude", "run", entry.profileId, "--"].map(shQuote).join(" ");
  return `exec ${command} "$@"`;
}

function launcherScript(entry: ClaudeLauncherEntry, realClaude: string, frogpCommand: string[]): string {
  if (process.platform === "win32") {
    const command = [...frogpCommand, "claude", "run", entry.profileId, "--"].map(cmdQuote).join(" ");
    return [
      "@echo off",
      `rem ${MANAGED_MARKER}. Do not edit by hand.`,
      `set "FROGP_REAL_CLAUDE=${realClaude.replace(/%/g, "%%")}"`,
      `${command} %*`,
      "",
    ].join("\r\n");
  }
  return [
    "#!/bin/sh",
    `# ${MANAGED_MARKER}. Do not edit by hand.`,
    `FROGP_REAL_CLAUDE=${shQuote(realClaude)}`,
    "export FROGP_REAL_CLAUDE",
    launcherExecLine(frogpCommand, entry),
    "",
  ].join("\n");
}


