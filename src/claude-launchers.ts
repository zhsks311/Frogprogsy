const LAUNCHER_RECOVERY_DIR = ".frogprogsy-launcher-recovery";
const LAUNCHER_RECOVERY_MANIFEST = "manifest.json";
const LAUNCHER_RECOVERY_CAPTURE = "captured";
const LAUNCHER_RECOVERY_OWNER = "owner";
const LAUNCHER_RECOVERY_OWNER_BYTES = "Generated by frogprogsy launcher recovery\n";
const LAUNCHER_RECOVERY_COPY_BUFFER_BYTES = 64 * 1024;
const MAX_MANAGED_LAUNCHER_BYTES = 1024 * 1024;
const MANAGED_WRITE_RECOVERY_SUFFIX = process.platform === "win32"
  ? `\r\nrem frogprogsy durable recovery ---------------------------------------------------------------- ${MANAGED_MARKER}\r\n`
  : `\n# frogprogsy durable recovery ---------------------------------------------------------------- ${MANAGED_MARKER}\n`;
const MANAGED_WRITE_RECOVERY_BYTES = Buffer.from(MANAGED_WRITE_RECOVERY_SUFFIX, "utf8");

function fsErrorCode(error: unknown): string | undefined {
  if (!error || typeof error !== "object" || !("code" in error)) return undefined;
  return typeof error.code === "string" ? error.code : undefined;
}

function readLauncherFdBuffer(
  fd: number,
  limit = LAUNCHER_SNIFF_BYTES,
  readChunk: LauncherReadChunk = readSync,
): Buffer {
  const size = Math.min(fstatSync(fd).size, limit);
  const buffer = Buffer.alloc(size);
  let offset = 0;
  while (offset < size) {
    const bytesRead = readChunk(fd, buffer, offset, size - offset, offset);
    if (!Number.isInteger(bytesRead) || bytesRead < 0 || bytesRead > size - offset) {
      throw new Error("managed launcher read made invalid progress");
    }
    if (bytesRead === 0) break;
    offset += bytesRead;
  }
  return offset === size ? buffer : buffer.subarray(0, offset);
}

function readLauncherFd(
  fd: number,
  limit = LAUNCHER_SNIFF_BYTES,
  readChunk: LauncherReadChunk = readSync,
): string {
  return readLauncherFdBuffer(fd, limit, readChunk).toString("utf8");
}

function classifyLauncherTarget(
  target: string,
  readChunk: LauncherReadChunk = readSync,
): LauncherTargetOwnership {
  let fd: number | undefined;
  try {
    const pathStat = lstatSync(target);
    if (pathStat.isSymbolicLink() || !pathStat.isFile()) return { kind: "foreign" };
    fd = openSync(target, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
    const opened = fstatSync(fd);
    if (!opened.isFile()
      || opened.dev !== pathStat.dev
      || opened.ino !== pathStat.ino) return { kind: "foreign" };
    const head = readLauncherFd(fd, LAUNCHER_SNIFF_BYTES, readChunk);
    if (opened.size > MAX_MANAGED_LAUNCHER_BYTES) {
      if (!head.includes(MANAGED_MARKER)) return { kind: "foreign" };
      if (opened.nlink !== 1) return { kind: "unsafe-managed" };
      return { kind: "unsafe-managed-size" };
    }
    const contentBytes = readLauncherFdBuffer(fd, opened.size + 1, readChunk);
    if (contentBytes.length !== opened.size) return { kind: "foreign" };
    const content = contentBytes.toString("utf8");
    const recoverySuffixPresent = contentBytes.length >= MANAGED_WRITE_RECOVERY_BYTES.length
      && contentBytes.subarray(-MANAGED_WRITE_RECOVERY_BYTES.length).equals(MANAGED_WRITE_RECOVERY_BYTES);
    if (!head.includes(MANAGED_MARKER) && !recoverySuffixPresent) return { kind: "foreign" };
    if (opened.nlink !== 1) return { kind: "unsafe-managed" };
    const requiredRecoveryBytes = recoverySuffixPresent ? 0 : MANAGED_WRITE_RECOVERY_BYTES.length;
    if (opened.size + requiredRecoveryBytes > MAX_MANAGED_LAUNCHER_BYTES) {
      return { kind: "unsafe-managed-size" };
    }
    return {
      kind: "managed",
      dev: opened.dev,
      ino: opened.ino,
      content,
      size: opened.size,
      sha256: createHash("sha256").update(contentBytes).digest("hex"),
      recoverySuffixPresent,
    };
  } catch (error) {
    return fsErrorCode(error) === "ENOENT" ? { kind: "absent" } : { kind: "foreign" };
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
  }
}

function pathHasIdentity(target: string, expected: ManagedTargetIdentity): boolean {
  try {
    const current = lstatSync(target);
    return current.isFile()
      && !current.isSymbolicLink()
      && current.dev === expected.dev
      && current.ino === expected.ino;
  } catch {
    return false;
  }
}

function managedLauncherFdMatches(
  fd: number,
  expected: ManagedTargetIdentity,
  readChunk: LauncherReadChunk = readSync,
): boolean {
  const current = fstatSync(fd);
  if (!current.isFile()
    || current.nlink !== 1
    || current.dev !== expected.dev
    || current.ino !== expected.ino
    || current.size !== expected.size) return false;
  const content = readLauncherFdBuffer(fd, expected.size + 1, readChunk);
  return content.length === expected.size
    && createHash("sha256").update(content).digest("hex") === expected.sha256;
}

function appendManagedLauncherRecovery(fd: number, position: number): void {
  const bytes = MANAGED_WRITE_RECOVERY_BYTES;
  let offset = 0;
  while (offset < bytes.length) {
    const written = writeSync(fd, bytes, offset, bytes.length - offset, position + offset);
    if (!Number.isInteger(written) || written <= 0 || written > bytes.length - offset) {
      throw new Error("managed launcher recovery append made no valid progress");
    }
    offset += written;
  }
  fsyncSync(fd);
}

function writeLauncherFd(fd: number, content: string, writeChunk: LauncherWriteChunk = writeSync): void {
  const bytes = Buffer.from(content, "utf8");
  let offset = 0;
  while (offset < bytes.length) {
    const written = writeChunk(fd, bytes, offset, bytes.length - offset, offset);
    if (!Number.isInteger(written) || written <= 0 || written > bytes.length - offset) {
      throw new Error("managed launcher write made no valid progress");
    }
    offset += written;
  }
  ftruncateSync(fd, bytes.length);
  if (process.platform !== "win32") fchmodSync(fd, 0o755);
  fsyncSync(fd);
}

function fsyncDirectory(path: string): boolean {
  let fd: number | undefined;
  try {
    fd = openSync(path, constants.O_RDONLY);
    fsyncSync(fd);
    return true;
  } catch {
    return process.platform === "win32";
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
  }
}

function unlinkGeneratedFileIfIdentity(path: string, dev: number, ino: number): void {
  try {
    const current = lstatSync(path);
    if (current.isFile() && !current.isSymbolicLink() && current.dev === dev && current.ino === ino) {
      unlinkSync(path);
    }
  } catch { /* remove only the generated path when its identity is still exact */ }
}

function publishManagedLauncher(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  target: string,
  entry: ClaudeLauncherEntry,
  ownership: LauncherTargetOwnership,
  content: string,
  beforePublish?: ClaudeLauncherSyncOptions["beforePublish"],
  readManagedLauncherChunk?: LauncherReadChunk,
  writeManagedLauncherChunk?: LauncherWriteChunk,
  syncDirectory: NonNullable<ClaudeLauncherSyncOptions["fsyncDirectory"]> = fsyncDirectory,
): boolean {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return false;
  if (ownership.kind === "managed") {
    let fd: number | undefined;
    try {
      fd = openSync(target, constants.O_RDWR | (constants.O_NOFOLLOW ?? 0));
      if (!managedLauncherFdMatches(fd, ownership, readManagedLauncherChunk)) return false;
      beforePublish?.(target, entry);
      if (!launcherDirectoryHasIdentity(binDir, binIdentity)
        || !pathHasIdentity(target, ownership)
        || !managedLauncherFdMatches(fd, ownership, readManagedLauncherChunk)) return false;
      if (!ownership.recoverySuffixPresent) appendManagedLauncherRecovery(fd, ownership.size);
      writeLauncherFd(fd, content, writeManagedLauncherChunk);
      return launcherDirectoryHasIdentity(binDir, binIdentity)
        && pathHasIdentity(target, ownership)
        && readLauncherFd(fd, Buffer.byteLength(content, "utf8") + 1, readManagedLauncherChunk) === content;
    } catch {
      return false;
    } finally {
      if (fd !== undefined) {
        try { closeSync(fd); } catch { /* best effort */ }
      }
    }
  }
  if (ownership.kind !== "absent") return false;

  const temporary = join(dirname(target), `.frogprogsy-launcher-${randomUUID()}.tmp`);
  let fd: number | undefined;
  let temporaryIdentity: { dev: number; ino: number } | undefined;
  try {
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return false;
    fd = openSync(
      temporary,
      constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0),
      0o755,
    );
    writeLauncherFd(fd, content);
    const temporaryStat = fstatSync(fd);
    temporaryIdentity = { dev: temporaryStat.dev, ino: temporaryStat.ino };
    beforePublish?.(target, entry);
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return false;
    linkSync(temporary, target);
    if (!syncDirectory(dirname(target))) {
      if (launcherDirectoryHasIdentity(binDir, binIdentity)) {
        unlinkGeneratedFileIfIdentity(target, temporaryStat.dev, temporaryStat.ino);
      }
      return false;
    }
    const published = lstatSync(target);
    return launcherDirectoryHasIdentity(binDir, binIdentity)
      && published.isFile()
      && !published.isSymbolicLink()
      && published.dev === temporaryStat.dev
      && published.ino === temporaryStat.ino;
  } catch {
    return false;
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
    if (temporaryIdentity && launcherDirectoryHasIdentity(binDir, binIdentity)) {
      unlinkGeneratedFileIfIdentity(temporary, temporaryIdentity.dev, temporaryIdentity.ino);
    }
  }
}

function launcherRecoveryRoot(binDir: string): string {
  return join(binDir, LAUNCHER_RECOVERY_DIR);
}

function recoveryRootIsOwned(recoveryRoot: string): boolean {
  let ownerFd: number | undefined;
  try {
    const rootStat = lstatSync(recoveryRoot);
    if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) return false;
    if (process.platform !== "win32" && (rootStat.mode & 0o777) !== 0o700) return false;
    const ownerPath = join(recoveryRoot, LAUNCHER_RECOVERY_OWNER);
    const ownerStat = lstatSync(ownerPath);
    if (!ownerStat.isFile() || ownerStat.isSymbolicLink() || ownerStat.nlink !== 1) return false;
    ownerFd = openSync(ownerPath, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
    return readLauncherFd(ownerFd, LAUNCHER_RECOVERY_OWNER_BYTES.length + 1) === LAUNCHER_RECOVERY_OWNER_BYTES;
  } catch {
    return false;
  } finally {
    if (ownerFd !== undefined) {
      try { closeSync(ownerFd); } catch { /* best effort */ }
    }
  }
}

function ownedRecoveryRoot(binDir: string, create: boolean): string | null {
  const recoveryRoot = launcherRecoveryRoot(binDir);
  try {
    lstatSync(recoveryRoot);
    return recoveryRootIsOwned(recoveryRoot) ? recoveryRoot : null;
  } catch (error) {
    if (!create || fsErrorCode(error) !== "ENOENT") return null;
  }

  let ownerFd: number | undefined;
  try {
    mkdirSync(recoveryRoot, { mode: 0o700 });
    const rootStat = lstatSync(recoveryRoot);
    if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) return null;
    const ownerPath = join(recoveryRoot, LAUNCHER_RECOVERY_OWNER);
    ownerFd = openSync(
      ownerPath,
      constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0),
      0o600,
    );
    writeFileSync(ownerFd, LAUNCHER_RECOVERY_OWNER_BYTES, "utf8");
    fsyncSync(ownerFd);
    closeSync(ownerFd);
    ownerFd = undefined;
    if (!fsyncDirectory(recoveryRoot) || !fsyncDirectory(binDir)) return null;
    return recoveryRootIsOwned(recoveryRoot) ? recoveryRoot : null;
  } catch {
    return null;
  } finally {
    if (ownerFd !== undefined) {
      try { closeSync(ownerFd); } catch { /* best effort */ }
    }
  }
}

function removeRecoveryOperation(operationDir: string): void {
  try {
    const capture = join(operationDir, LAUNCHER_RECOVERY_CAPTURE);
    try {
      lstatSync(capture);
      return;
    } catch (error) {
      if (fsErrorCode(error) !== "ENOENT") return;
    }
    for (const fileName of [
      LAUNCHER_RECOVERY_MANIFEST,
      "hardlink-preflight",
      "hardlink-preflight-link",
    ]) {
      try { unlinkSync(join(operationDir, fileName)); } catch { /* already absent */ }
    }
    rmdirSync(operationDir);
  } catch { /* generated recovery only */ }
}

function createRemovalRecovery(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  target: string,
  ownership: ManagedTargetIdentity,
): { operationDir: string; capture: string } | null {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return null;
  const recoveryRoot = ownedRecoveryRoot(binDir, true);
  if (!recoveryRoot || !launcherDirectoryHasIdentity(binDir, binIdentity)) return null;
  const operationDir = join(recoveryRoot, randomUUID());
  try {
    mkdirSync(operationDir, { mode: 0o700 });

    const preflight = join(operationDir, "hardlink-preflight");
    const preflightLink = join(operationDir, "hardlink-preflight-link");
    let preflightFd: number | undefined;
    try {
      preflightFd = openSync(preflight, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL, 0o600);
      writeFileSync(preflightFd, "frogprogsy launcher recovery", "utf8");
      fsyncSync(preflightFd);
    } finally {
      if (preflightFd !== undefined) closeSync(preflightFd);
    }
    linkSync(preflight, preflightLink);
    unlinkSync(preflightLink);
    unlinkSync(preflight);

    const manifest: LauncherRemovalManifest = {
      schemaVersion: 2,
      phase: "capture-pending",
      targetName: basename(target),
      expected: {
        dev: ownership.dev,
        ino: ownership.ino,
        size: ownership.size,
        sha256: ownership.sha256,
      },
    };
    const manifestPath = join(operationDir, LAUNCHER_RECOVERY_MANIFEST);
    let manifestFd: number | undefined;
    try {
      manifestFd = openSync(
        manifestPath,
        constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0),
        0o600,
      );
      writeFileSync(manifestFd, JSON.stringify(manifest) + "\n", "utf8");
      fsyncSync(manifestFd);
    } finally {
      if (manifestFd !== undefined) closeSync(manifestFd);
    }
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)
      || !recoveryRootIsOwned(recoveryRoot)
      || !fsyncDirectory(operationDir)
      || !fsyncDirectory(recoveryRoot)) {
      if (launcherDirectoryHasIdentity(binDir, binIdentity)) removeRecoveryOperation(operationDir);
      return null;
    }
    return { operationDir, capture: join(operationDir, LAUNCHER_RECOVERY_CAPTURE) };
  } catch {
    if (launcherDirectoryHasIdentity(binDir, binIdentity)) removeRecoveryOperation(operationDir);
    return null;
  }
}

function readRemovalManifest(
  operationDir: string,
  readChunk: LauncherReadChunk = readSync,
): LauncherRemovalManifest | null {
  let fd: number | undefined;
  try {
    const manifestPath = join(operationDir, LAUNCHER_RECOVERY_MANIFEST);
    const manifestStat = lstatSync(manifestPath);
    if (!manifestStat.isFile() || manifestStat.isSymbolicLink() || manifestStat.nlink !== 1) return null;
    fd = openSync(manifestPath, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
    const opened = fstatSync(fd);
    if (!opened.isFile()
      || opened.nlink !== 1
      || opened.dev !== manifestStat.dev
      || opened.ino !== manifestStat.ino) return null;
    const manifest = JSON.parse(readLauncherFd(fd, LAUNCHER_SNIFF_BYTES, readChunk));
    if ((manifest?.schemaVersion !== 1 && manifest?.schemaVersion !== 2)
      || manifest.phase !== "capture-pending") return null;
    if (typeof manifest.targetName !== "string" || basename(manifest.targetName) !== manifest.targetName) return null;
    if (manifest.schemaVersion === 2) {
      const expected = manifest.expected;
      if (!expected
        || !Number.isInteger(expected.dev)
        || !Number.isInteger(expected.ino)
        || !Number.isSafeInteger(expected.size)
        || expected.size < 0
        || typeof expected.sha256 !== "string"
        || !/^[0-9a-f]{64}$/.test(expected.sha256)) return null;
    }
    return manifest as LauncherRemovalManifest;
  } catch {
    return null;
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* best effort */ }
    }
  }
}

function restoreCapturedForeign(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  capture: string,
  target: string,
  operationDir: string,
  afterForeignRestore?: (target: string, capture: string) => void,
  syncDirectory: NonNullable<ClaudeLauncherSyncOptions["fsyncDirectory"]> = fsyncDirectory,
): "restored" | "never-captured" | "pending" {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return "pending";
  let captured;
  try {
    captured = lstatSync(capture);
  } catch (error) {
    if (fsErrorCode(error) !== "ENOENT") return "pending";
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return "pending";
    removeRecoveryOperation(operationDir);
    try {
      lstatSync(operationDir);
      return "pending";
    } catch (cleanupError) {
      return fsErrorCode(cleanupError) === "ENOENT" ? "never-captured" : "pending";
    }
  }
  try {
    lstatSync(target);
    return "pending";
  } catch (error) {
    if (fsErrorCode(error) !== "ENOENT") return "pending";
  }

  const temporary = join(operationDir, `.restore-${randomUUID()}.tmp`);
  let captureFd: number | undefined;
  let temporaryFd: number | undefined;
  let temporaryIdentity: { dev: number; ino: number } | undefined;
  try {
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return "pending";
    if (captured.isFile() && !captured.isSymbolicLink()) {
      captureFd = openSync(capture, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
      const openedCapture = fstatSync(captureFd);
      if (!openedCapture.isFile()
        || openedCapture.dev !== captured.dev
        || openedCapture.ino !== captured.ino) return "pending";

      temporaryFd = openSync(
        temporary,
        constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0),
        0o600,
      );
      const openedTemporary = fstatSync(temporaryFd);
      temporaryIdentity = { dev: openedTemporary.dev, ino: openedTemporary.ino };
      const buffer = Buffer.allocUnsafe(LAUNCHER_RECOVERY_COPY_BUFFER_BYTES);
      for (;;) {
        const bytesRead = readSync(captureFd, buffer, 0, buffer.length, null);
        if (bytesRead === 0) break;
        let bytesWritten = 0;
        while (bytesWritten < bytesRead) {
          bytesWritten += writeSync(temporaryFd, buffer, bytesWritten, bytesRead - bytesWritten);
        }
      }
      if (process.platform !== "win32") fchmodSync(temporaryFd, openedCapture.mode & 0o7777);
      fsyncSync(temporaryFd);
      if (!syncDirectory(operationDir)
        || !launcherDirectoryHasIdentity(binDir, binIdentity)) return "pending";
      linkSync(temporary, target);
    } else if (captured.isSymbolicLink()) {
      symlinkSync(readlinkSync(capture), target, "file");
    } else {
      return "pending";
    }
    afterForeignRestore?.(target, capture);
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return "pending";
    if (!syncDirectory(dirname(target))) return "pending";
    return "restored";
  } catch {
    return "pending";
  } finally {
    if (captureFd !== undefined) {
      try { closeSync(captureFd); } catch { /* best effort */ }
    }
    if (temporaryFd !== undefined) {
      try { closeSync(temporaryFd); } catch { /* best effort */ }
    }
    if (temporaryIdentity && launcherDirectoryHasIdentity(binDir, binIdentity)) {
      unlinkGeneratedFileIfIdentity(temporary, temporaryIdentity.dev, temporaryIdentity.ino);
    }
  }
}

function finishRemovalRecovery(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  operationDir: string,
  manifest: LauncherRemovalManifest,
  readManagedLauncherChunk?: LauncherReadChunk,
  afterForeignRestore?: (target: string, capture: string) => void,
  syncDirectory: NonNullable<ClaudeLauncherSyncOptions["fsyncDirectory"]> = fsyncDirectory,
): { removed: boolean; warning?: string } {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
    return { removed: false, warning: `launcher ${manifest.targetName} cleanup deferred; launcher directory changed` };
  }
  const capture = join(operationDir, LAUNCHER_RECOVERY_CAPTURE);
  const target = join(binDir, manifest.targetName);
  const capturedOwnership = classifyLauncherTarget(capture, readManagedLauncherChunk);
  const expected = manifest.expected;
  const capturedMatchesExpected = capturedOwnership.kind === "managed"
    && expected !== undefined
    && capturedOwnership.dev === expected.dev
    && capturedOwnership.ino === expected.ino
    && capturedOwnership.size === expected.size
    && capturedOwnership.sha256 === expected.sha256;
  if (capturedMatchesExpected) {
    try {
      if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
        return { removed: false, warning: `launcher ${manifest.targetName} cleanup deferred; launcher directory changed` };
      }
      unlinkSync(capture);
      if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
        return { removed: false, warning: `launcher ${manifest.targetName} cleanup deferred; launcher directory changed` };
      }
      removeRecoveryOperation(operationDir);
      return { removed: true };
    } catch {
      return { removed: false, warning: `launcher ${manifest.targetName} cleanup deferred; generated recovery is still pending` };
    }
  }
  const foreignRecovery = restoreCapturedForeign(
    binDir,
    binIdentity,
    capture,
    target,
    operationDir,
    afterForeignRestore,
    syncDirectory,
  );
  if (foreignRecovery === "never-captured") return { removed: false };
  if (foreignRecovery === "restored") {
    return {
      removed: false,
      warning: `launcher ${manifest.targetName} cleanup deferred; the changed target was restored; manual recovery/cleanup is required before removing the preserved capture`,
    };
  }
  return { removed: false, warning: `launcher ${manifest.targetName} cleanup deferred; preserved recovery requires attention` };
}

function recoverLauncherRemovals(
  binDir: string,
  binIdentity: LauncherDirectoryIdentity,
  readManagedLauncherChunk?: LauncherReadChunk,
  afterForeignRestore?: (target: string, capture: string) => void,
  syncDirectory: NonNullable<ClaudeLauncherSyncOptions["fsyncDirectory"]> = fsyncDirectory,
): string[] {
  if (!launcherDirectoryHasIdentity(binDir, binIdentity)) return [];
  const recoveryRoot = ownedRecoveryRoot(binDir, false);
  if (!recoveryRoot || !launcherDirectoryHasIdentity(binDir, binIdentity)) return [];
  let operationNames: string[];
  try {
    operationNames = readdirSync(recoveryRoot);
  } catch {
    return [];
  }
  const warnings: string[] = [];
  for (const operationName of operationNames) {
    if (!launcherDirectoryHasIdentity(binDir, binIdentity)) {
      warnings.push("launcher cleanup deferred; launcher directory changed during recovery");
      break;
    }
    if (operationName === LAUNCHER_RECOVERY_OWNER) continue;
    const operationDir = join(recoveryRoot, operationName);
    try {
      const operationStat = lstatSync(operationDir);
      if (!operationStat.isDirectory() || operationStat.isSymbolicLink()) {
        warnings.push("launcher cleanup deferred; an unsafe recovery entry was preserved");
        continue;
      }
    } catch {
      continue;
    }
    const manifest = readRemovalManifest(operationDir, readManagedLauncherChunk);
    if (!manifest) {
      warnings.push("launcher cleanup deferred; an unreadable recovery record was preserved");
      continue;
    }
    const outcome = finishRemovalRecovery(
      binDir,
      binIdentity,
      operationDir,
      manifest,
      readManagedLauncherChunk,
      afterForeignRestore,
      syncDirectory,
    );
    if (outcome.warning) warnings.push(outcome.warning);
  }
  return warnings;
}

